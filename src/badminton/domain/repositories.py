from typing import Protocol
import pandas as pd

class RacketRepository(Protocol):
    def find_under_budget(self, max_price: float) -> pd.DataFrame: ...
    def find_by_name(self, name: str, limit: int) -> pd.DataFrame: ...
    def list_page(self, **query) -> dict: ...

class ShoeRepository(Protocol):
    def find_fitting(self, gender: str, size_eu: float, max_price: float | None) -> pd.DataFrame: ...
    def find_by_name(self, name: str, limit: int) -> pd.DataFrame: ...
    def list_page(self, **query) -> dict: ...